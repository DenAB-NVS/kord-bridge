#!/data/data/com.termux/files/usr/bin/bash
# 0113 — положить на Руку скрипт аварийного восстановления сторожа (по слову владельца 14.10).
# Не выполняет восстановление — только сохраняет кнопку отката для Дениса.
echo "== 0113: кнопка отката на Руку =="
D="$HOME/kord-восстановление"; mkdir -p "$D"
scp -o BatchMode=yes -o ConnectTimeout=25 root@45.152.198.192:/root/kord-restore-сторожа.sh "$D/восстановить-сторожа.sh" || { echo "scp упал"; exit 1; }
[ -s "$D/восстановить-сторожа.sh" ] || { echo "файл пуст — не принял"; exit 1; }
echo "сохранён: $D/восстановить-сторожа.sh"
echo "если оба агента упали, Денису в Termux: bash ~/kord-восстановление/восстановить-сторожа.sh"
echo "== 0113: конец =="
