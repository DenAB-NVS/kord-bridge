#!/usr/bin/env bash
# Задание моста: боевая отправка рассылки
# Слово владельца «отправляй» получено 25.09.2026, 21:13 MSK
set -u
R="/root/рассылка"
cd "$R" || { echo "— НЕТ ПАПКИ РАССЫЛКИ"; exit 0; }

if [ ! -f конфиг.json ]; then
  echo "— ОТПРАВКА НЕВОЗМОЖНА: нет конфиг.json (задание 11 не связало)"
  exit 0
fi

nohup python3 otpravka.py >> рассылка.log 2>&1 &
PID=$!
echo "— рассылка запущена в фоне, PID $PID"
sleep 25
echo "— первые строки лога:"
head -8 рассылка.log 2>/dev/null || true
echo "— отчёт (если уже пишется):"
head -8 отчёт-рассылки.txt 2>/dev/null || echo "отчёт появится по мере отправки"
